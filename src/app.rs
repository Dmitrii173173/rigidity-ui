    fn status_line(&self, palette: &Palette) -> (Color32, String) {
        if let Some(error) = &self.failure {
            return (palette.low, error.to_string());
        }
        if let Some(path) = &self.reading {
            return (palette.medium, format!("reading {}…", file_name(path)));
        }
        if let Some((name, seconds)) = &self.saved {
            return (palette.high, format!("wrote {name} in {seconds:.2} s"));
        }
        match &self.work {
            Work::Running { step, .. } => {
                let text = match step {
                    _ if !self.iterations.is_empty() => format!(
                        "iteration {} · rmse {:.2e} m   esc to stop",
                        self.iterations.len(),
                        self.iterations.last().map_or(f64::NAN, |it| it.rmse)
                    ),
                    Some(Step { label, done, total }) if *total > 0 => format!(
                        "{label} · {:.0}%   esc to stop",
                        100.0 * *done as f32 / *total as f32
                    ),
                    _ => "preparing…   esc to stop".to_owned(),
                };
                return (palette.medium, text);
            }
            // A stop between stages is the honest granularity while
            // preparing; inside the solver it is per accepted iteration.
            Work::Cancelled => return (palette.faint, "stopped".to_owned()),
            Work::Idle => {}
        }
        // A measurement only gets the strip when nothing louder is
        // happening, which is most of the time: it is a second or two.
        if let Some(on_source) = self.pairing {
            return (
                palette.accent,
                format!(
                    "{} · click the matching point on the {}   esc to stop",
                    match self.pairs.len() {
                        0 => "no pairs yet".to_owned(),
                        1 => "1 pair".to_owned(),
                        many => format!("{many} pairs"),
                    },
                    if on_source { "source" } else { "target" }
                ),
            );
        }
        if self.measuring_points {
            return (
                palette.accent,
                match self.measurement.len() {
                    0 => "click a point   M or esc to stop".to_owned(),
                    1 => "click the other one".to_owned(),
                    _ => "click again to start over   M to stop".to_owned(),
                },
            );
        }
        if let Some(Measuring { step, .. }) = &self.measuring {
            let text = match step {
                Some(Step { label, done, total }) if *total > 0 => format!(
                    "{label} · {:.0}%   esc to stop",
                    100.0 * *done as f32 / *total as f32
                ),
                _ => "measuring…   esc to stop".to_owned(),
            };
            return (palette.medium, text);
        }
        match &self.outcome {
            Outcome::Registration { outcome, seconds } => (
                if self.trusted() {
                    palette.high
                } else {
                    palette.medium
                },
                format!(
                    "rmse {:.2e} m · {} correspondences · {} iterations · {} · {:.2} s",
                    outcome.result.rmse,
                    thousands(outcome.result.correspondences),
                    outcome.result.iterations,
                    if outcome.result.converged {
                        "converged"
                    } else {
                        "stopped at the iteration cap"
                    },
                    seconds
                ),
            ),
            Outcome::Analysis {
                surface, seconds, ..
            } => (
                palette.high,
                format!(
                    "{} points, {} after downsampling · analysed in {:.2} s",
                    self.target()
                        .map_or(0, |entry| entry.cloud.len())
                        .pipe(thousands),
                    thousands(surface.cloud.len()),
                    seconds
                ),
            ),
            Outcome::Nothing => (palette.faint, "drop a PLY file here".to_owned()),
        }
    }

