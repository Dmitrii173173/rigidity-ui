                        let held = entry
                            .field
                            .as_ref()
                            .is_some_and(|field| field.source == source);
                        let response = ui.add(
                            egui::Button::new(
                                RichText::new(source.label()).size(11.0).color(if held {
                                    palette.text
                                } else {
                                    palette.muted
                                }),
                            )
                            .fill(if held {
                                palette.line
                            } else {
                                Color32::TRANSPARENT
                            }),
                        );
