/// How many points the viewport can draw and still turn smoothly.
///
/// Measured, not guessed (S1's level-of-detail gate; the numbers and the
/// decision are in PLAN.md §8). This renderer is fill-bound and its cost is
/// linear in points at about 6.2 ms per million on the machine the gate was
/// run on: two million holds 60 fps, five million gives 30, twenty gives 8.
/// Twenty scans of a million points each — the case stage three exists for
/// — is seven times over.
///
/// A single number rather than a per-machine measurement because the
/// consequence of being wrong is a preview that is slightly too coarse or
/// slightly too slow for one frame, and a viewer that benchmarks itself on
/// startup is a viewer that does something inexplicable on startup.
const VIEWPORT_BUDGET: usize = 2_700_000;

/// How long after the last camera movement the full clouds come back.
///
/// Long enough not to flicker between the two while someone is turning the
/// scene in short strokes, short enough that letting go and looking feels
/// like the same gesture.
const SETTLE: f64 = 0.2;

/// Marks a preview's coordinates in the renderer's cache.
///
/// The renderer keys buffers by a `u64` it never interprets, so the two
/// copies of one cloud need two keys. Bit 62; the solver's own downsampled
/// cloud already has bit 63.
const COARSE: u64 = 1 << 62;

/// A cloud in the scene.
///
/// The scene is a list, not two slots. *Source* and *target* are roles
/// assigned to two of its entries, which is what lets a third cloud be
/// loaded for context, or the roles be reassigned without reloading
/// anything.
struct Entry {
    /// Identity. Never reused, so the renderer can cache coordinates under
    /// it and the engine can tell whether its own cache still holds.
    id: u64,
    path: PathBuf,
    /// Generated by the application rather than read from disk.
    generated: bool,
    cloud: Arc<PointCloud>,
    min: na::Vector3<f64>,
    max: na::Vector3<f64>,
    seconds: f64,
    /// How this scan is prepared before the solver sees it.
    ///
    /// Per scan and not per application: a survey is not made of clouds at
    /// one density, and a station taken up against a wall wants a finer
    /// voxel than one taken across a hall. When every scan carries the same
    /// values — which is what happens unless somebody changes one — the
    /// behaviour is exactly what it was before they were per scan.
    prepare: PrepareParams,
    /// A coarse copy, drawn instead while the camera is moving and the
    /// scene is over budget. `None` for a cloud small enough to be its own
    /// preview.
    coarse: Option<Arc<PointCloud>>,
    /// Where it sits: the motion carrying its own coordinates into the
    /// survey frame.
    ///
    /// Stage two had one pose in the whole application, belonging to the
    /// registration rather than to a cloud, because two clouds need only
    /// one answer to "where is it". Twenty scans each need their own, and
    /// a pose is the non-destructive way to hold it — the points are never
    /// rewritten, so placing a scan costs a matrix and nothing else.
    pose: Se3,
    /// Hidden entries keep their place, their colour and their buffers.
    visible: bool,
    /// The scalar it is currently coloured by, if any.
    field: Option<Field>,
    /// Bumped whenever those values change — not when a clamp moves, which
    /// is a uniform and not an upload.
    field_version: u64,
    /// Its position in the colour series, fixed when it was loaded so that
    /// removing an earlier cloud does not recolour the rest.
    tint: usize,
}

impl Entry {
    fn name(&self) -> &str {
        self.path
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or("cloud")
    }

    fn held(&self) -> Held {
        Held {
            cloud: Arc::clone(&self.cloud),
            generation: self.id,
        }
    }
}

/// What went wrong, in whichever vocabulary owns the answer.
///
/// The library's errors and the project format's are different kinds of
/// fact — one is about points, the other about a line of text somebody may
/// have edited — and flattening them into a string at the point they occur
/// would throw away the only structure they have while it is still useful.
enum Failure {
    /// `rigidity` said so.
    Pipeline(PipelineError),
    /// The project file said so, or would not say anything at all.
    Project {
        /// The file that was being read.
        path: PathBuf,
        /// What was wrong with it.
        problem: project::Error,
    },
}

impl fmt::Display for Failure {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Pipeline(error) => write!(f, "{error}"),
            Self::Project { path, problem } => write!(f, "{}: {problem}", path.display()),
        }
    }
}

/// What the engine is doing for us.
enum Work {
    Idle,
    Running { id: u64, step: Option<Step> },
    Cancelled,
}

/// What a click is being asked for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Purpose {
    /// An end of a measurement.
    Measure,
    /// One half of a correspondence, on the source or on the target.
    Pair { on_source: bool },
}

/// What a lasso enclosed.
struct Selection {
    /// Which cloud the indices are into.
    entry: u64,
    indices: Arc<Vec<u32>>,
}

/// A slab of the scene to look inside.
///
/// A cross-section is a view, not an edit: nothing is removed, the points
/// outside are simply not drawn. Cutting a cloud in order to see into it
/// and then having to undo the cut is the arrangement this avoids.
#[derive(Debug, Clone, Copy)]
struct Section {
    on: bool,
    /// Which axis of the drawing frame it cuts along.
    axis: usize,
    /// Where the slab sits along it, metres.
    position: f32,
    /// How thick it is, metres.
    thickness: f32,
}

impl Default for Section {
    fn default() -> Self {
        Self {
            on: false,
            axis: 2,
            position: 0.0,
            thickness: 1.0,
        }
    }
}

impl Section {
    /// The unit normal, and the two offsets along it that bound the slab.
    ///
    /// Equal offsets mean no cross-section, which is what the renderer
    /// reads when this is switched off.
    fn slab(&self) -> ([f32; 3], f32, f32) {
        let mut normal = [0.0; 3];
        normal[self.axis.min(2)] = 1.0;
        if !self.on {
            return (normal, 0.0, 0.0);
        }
        let half = (self.thickness * 0.5).max(1e-6);
        (normal, self.position - half, self.position + half)
    }

    /// Fits the slab to a scene it has not seen before.
    fn frame(&mut self, min: na::Point3<f32>, max: na::Point3<f32>) {
        let centre = na::center(&min, &max);
        self.position = centre[self.axis.min(2)];
        self.thickness = ((max - min).amax() * 0.1).max(1e-3);
    }
}

/// A distance field on its way.
#[derive(Debug, Clone, Copy)]
struct Measuring {
    /// The request, so late answers to earlier questions can be ignored.
    request: u64,
    /// Which cloud it is about, so a registration finishing mid-flight can
    /// ask the question again at the pose it just found.
    entry: u64,
    step: Option<Step>,
}

/// What it has produced.
enum Outcome {
    Nothing,
    Analysis {
        analysis: Box<Analysis>,
        surface: Box<Surface>,
        seconds: f64,
    },
    Registration {
        outcome: Box<Registration>,
        seconds: f64,
    },
}

/// One σ row's contribution field, kept until the row or the report
/// changes.
struct Contribution {
    row: usize,
    answered: u64,
    values: Arc<Vec<f32>>,
    span: [f32; 2],
}

